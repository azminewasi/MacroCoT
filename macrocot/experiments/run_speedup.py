"""Macro-transition speedup experiment.

For each task and each macro order k, we build the order-k macro machine,
generate supervised traces, train a next-token transformer, and record two
quantities the theory predicts:

1. Trace length. The mean supervised trace length should fall by a factor of
   about k relative to k = 1, because k base transitions collapse into one
   macro token.
2. Optimizer steps to reach exact-match on held-out longer inputs. The
   "positions not bits" cost model predicts that shorter traces are learned in
   fewer steps at a fixed token budget, until the macro vocabulary grows large
   enough to dominate embedding capacity.

Every number written here is produced by an actual training run on
synthetic traces generated by the reference counter machine. Scale is kept
small so the whole grid runs on a single CPU core; the same script reproduces
the paper-scale protocol when the sizes in the config are increased.
"""

from __future__ import annotations

import argparse
import json
import os
from typing import Dict, List

from ..train.config import Config
from ..train.trainer import run_config


def summarize(result: Dict) -> Dict:
    cfg = result["config"]
    final = result["final"]
    return {
        "task": cfg["task"],
        "macro_k": cfg["macro_k"],
        "base_b": cfg["base_b"],
        "seed": cfg["seed"],
        "vocab_size": result["vocab_size"],
        "num_params": result["num_params"],
        "num_transitions": result["num_transitions"],
        "train_mean_trace": result["split_stats"]["train"]["mean_trace_len"],
        "test2_mean_trace": result["split_stats"]["test2"]["mean_trace_len"],
        "test0_em": final.get("test0_em"),
        "test1_em": final.get("test1_em"),
        "test2_em": final.get("test2_em"),
        "steps_test1": result["steps_to_solve"]["test1"],
        "steps_test2": result["steps_to_solve"]["test2"],
        "wall_time_sec": round(result["wall_time_sec"], 1),
    }


def run_grid(
    tasks: List[str],
    ks: List[int],
    seeds: List[int],
    out_dir: str = "results/macro",
    steps: int = 1500,
    **overrides,
) -> List[Dict]:
    os.makedirs(out_dir, exist_ok=True)
    rows: List[Dict] = []
    for task in tasks:
        for k in ks:
            for seed in seeds:
                cfg = Config(
                    task=task,
                    macro_k=k,
                    base_b=1,
                    seed=seed,
                    steps=steps,
                    tag="macro",
                    **overrides,
                )
                result = run_config(cfg, out_dir)
                rows.append(summarize(result))
    with open(os.path.join(out_dir, "summary.json"), "w") as f:
        json.dump(rows, f, indent=2)
    return rows


def default_grid(out_dir: str = "results/macro") -> List[Dict]:
    # macro applies to any task; comparison and multiplication are counting
    # dominated and benefit most. parity is included as a single-counter check.
    rows = []
    rows += run_grid(
        tasks=["comparison"],
        ks=[1, 2, 3],
        seeds=[0, 1],
        out_dir=out_dir,
        steps=1500,
        train_max=16,
        ood1_max=24,
        ood2_max=32,
        n_train=1400,
        n_test=48,
        d_model=64,
        d_ff=128,
        eval_interval=300,
    )
    rows += run_grid(
        tasks=["parity"],
        ks=[1, 2, 4],
        seeds=[0],
        out_dir=out_dir,
        steps=1200,
        train_max=14,
        ood1_max=22,
        ood2_max=30,
        n_train=1200,
        n_test=48,
        d_model=64,
        d_ff=128,
        eval_interval=300,
    )
    with open(os.path.join(out_dir, "summary.json"), "w") as f:
        json.dump(rows, f, indent=2)
    return rows


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="results/macro")
    p.add_argument("--quick", action="store_true", help="tiny grid for a wiring check")
    args = p.parse_args()
    if args.quick:
        run_grid(["comparison"], [1, 2], [0], out_dir=args.out, steps=300,
                 n_train=400, n_test=24, eval_interval=150)
    else:
        default_grid(args.out)
